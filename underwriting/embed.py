#!/usr/bin/env python3
"""Copy the engine sources into exparsed.html, which runs them in the browser through Pyodide.

Run after changing any file in SOURCES:  python underwriting/embed.py
tests/test_engine.py fails while the page copy differs from these files.
"""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAGE = HERE.parent / "exparsed.html"
SOURCES = {
    "uw-src-engine": "engine/uw.py",
    "uw-src-checker": "checker/validate_report.py",
    "uw-src-adapter": "adapter/exparsed_adapter.py",
    "uw-src-judge": "prompts/judge.md",
}
BEGIN = "<!-- UW-EMBED:BEGIN generated by underwriting/embed.py, do not edit -->"
END = "<!-- UW-EMBED:END -->"


def block():
    parts = [BEGIN]
    for id_, rel in SOURCES.items():
        text = (HERE / rel).read_text(encoding="utf-8")
        # The HTML parser would end or garble a script element at either sequence.
        if "</script" in text.lower() or "<!--" in text:
            sys.exit(
                f"embed: {rel} contains '</script' or '<!--' and cannot sit in a script element"
            )
        parts.append(
            f'<script type="text/plain" id="{id_}" data-uw-path="{rel}">{text}</script>'
        )
    parts.append(END)
    return "\n".join(parts)


def embedded(page_text):
    return page_text[page_text.index(BEGIN) : page_text.index(END) + len(END)]


if __name__ == "__main__":
    page = PAGE.read_text(encoding="utf-8")
    PAGE.write_text(page.replace(embedded(page), block()), encoding="utf-8")
    print(f"embedded {len(SOURCES)} files into {PAGE.name}")
